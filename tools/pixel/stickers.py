def render(name, art, out):
    rows = [r for r in art.strip('\n').split('\n')]
    px = {}
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch != '.':
                px[(x + 2, y + 2)] = PAL[ch]
    # white die-cut edge: two pixels around everything
    edge = set()
    for (x, y) in px:
        for dx in range(-2, 3):
            for dy in range(-2, 3):
                if abs(dx) + abs(dy) <= 3 and (x + dx, y + dy) not in px:
                    edge.add((x + dx, y + dy))
    w = max(len(r) for r in rows) + 4
    h = len(rows) + 4
    rects = [f'<rect x="{x}" y="{y}" width="1" height="1" fill="#ffffff"/>' for (x, y) in sorted(edge)]
    rects += [f'<rect x="{x}" y="{y}" width="1" height="1" fill="{c}"/>' for (x, y), c in sorted(px.items())]
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w * 6}" height="{h * 6}" '
           f'shape-rendering="crispEdges">' + ''.join(rects) + '</svg>\n')
    open(os.path.join(out, f'sticker-{name}.svg'), 'w').write(svg)
    print(name, w, h)


for n, a in ART.items():
    render(n, a, sys.argv[1])
